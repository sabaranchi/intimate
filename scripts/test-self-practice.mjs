import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const source=readFileSync(new URL('../src/utils/selfPractice.js',import.meta.url),'utf8')
const {normalizePractice,localDay,personContext,OS_QUESTIONS,PRINCIPLES}=await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`)
const corpus=JSON.parse(readFileSync(new URL('../src/utils/hanshengCorpus.json',import.meta.url),'utf8'))
assert.equal(corpus.scenes.length,100)
assert.equal(corpus.templates.length,50)
assert.equal(corpus.phases.length,13)
assert.equal(corpus.guides.length,4)
assert.deepEqual(corpus.days.map(x=>x.id),Array.from({length:365},(_,i)=>i+1))
assert.ok(corpus.scenes.every(x=>x.title&&x.text&&x.category))
assert.ok(corpus.templates.every(x=>x.title&&x.text))
assert.equal(OS_QUESTIONS.length,7)
assert.equal(PRINCIPLES.length,8)
for(const invalid of [null,[],false,'bad']) assert.equal(normalizePractice(invalid).day,1)
for(const day of [-1,0,366,1.5,'20']) assert.equal(normalizePractice({day}).day,1)
for(const day of [1,170,365]) assert.equal(normalizePractice({day}).day,day)
assert.deepEqual(normalizePractice({pins:[1,'scene-1',null],daily:[],training:false}).pins,['scene-1'])
assert.deepEqual(normalizePractice({daily:[]}).daily,{})
assert.equal(localDay(new Date(2026,8,14,0,1)),'2026-09-14')
assert.deepEqual(personContext(null),[])
const person={workplace:'職場',favourites:['コーヒー'],hobbies:['散歩'],communication:{recentTopics:'展示'},notes:{wants:'旅行',worries:'締切'}}
assert.ok(personContext(person).some(([k,v])=>k==='気にかけたいこと'&&v==='締切'))
assert.ok(personContext({communication:{conversationLog:[{date:'2026-09-01',topics:'古い話'},{date:'2026-09-14',topics:'新しい話',wantToAsk:'続きを聞く'}]}}).some(([k,v])=>k==='最近の話'&&v==='新しい話'))
const record={name:'テスト',values:'信用',practice:normalizePractice({day:365,pins:['trust'],daily:{'2026-09-14':{focus:'聞く',good:'提案した'}},preparations:{person1:{want:'本人の希望'}},training:{365:{done:true,note:'振り返り'}},monthly:{'2026-09':{胆力:7,evidence:'一歩進めた'}}})}
const restored=JSON.parse(JSON.stringify({format:'intimate-backup',version:2,self:record,people:[],assets:{}}))
assert.deepEqual(restored.self,record)
assert.deepEqual(normalizePractice(restored.self.practice),record.practice)
console.log('PASS: corpus completeness, day boundaries, normalization, person context, local dates, backup round-trip')
