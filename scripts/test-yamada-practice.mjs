import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const source=readFileSync(new URL('../src/utils/yamadaPractice.js',import.meta.url),'utf8')
const {PRACTICES,PRACTICE_GROUPS,practiceState,activePractice,nextPractice,completedPractices,choosePractice,completePractice,reopenPractice}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'))
assert.equal(PRACTICES.length,12)
assert.equal(new Set(PRACTICES.map(x=>x.id)).size,12)
for(let group=0;group<PRACTICE_GROUPS.length;group++)assert.equal(PRACTICES.filter(x=>x.group===group).length,3)
assert.ok(PRACTICES.every(x=>['title','action','care','clear'].every(k=>typeof x[k]==='string'&&x[k].length)))
assert.equal(activePractice({}),null)
assert.equal(nextPractice({}).id,'welcome')
for(const malformed of [null,[],{},'bad'])assert.doesNotThrow(()=>practiceState({yamadaPractice:malformed}))
assert.equal(activePractice({yamadaPractice:{activeId:'bad'}}),null)
const old={name:'self',gender:'男',notes:'keep',practice:{oldRecords:[1]},yamadaMode:'friends',yamadaPractice:{futureField:'keep',entries:{future:{completed:true,note:'keep'}}}}
const before=structuredClone(old)
const started=choosePractice(old,'hello')
assert.equal(activePractice(started).id,'hello')
assert.equal(completedPractices(started).length,0)
const completed=completePractice(started,'hello','  あいさつした  ','2026-09-25')
assert.equal(completedPractices(completed).length,1)
assert.equal(completed.yamadaPractice.entries.hello.note,'あいさつした')
assert.equal(completed.yamadaPractice.entries.hello.date,'2026-09-25')
assert.deepEqual(old,before,'no mutation of previous data')
assert.deepEqual(completed.practice,old.practice)
assert.equal(completed.notes,'keep')
assert.equal(completed.yamadaPractice.futureField,'keep')
assert.deepEqual(completed.yamadaPractice.entries.future,old.yamadaPractice.entries.future)
assert.equal(completedPractices(completePractice(completed,'hello','again','2026-09-26')).length,1,'no duplicate clears')
const reopened=reopenPractice(completed,'hello')
assert.equal(completedPractices(reopened).length,0)
assert.equal(reopened.yamadaPractice.entries.hello.note,'あいさつした','retry must preserve notes')
const paused=choosePractice(completed,null)
assert.equal(activePractice(paused),null)
assert.equal(completedPractices(paused).length,1)
for(const fn of [choosePractice,completePractice,reopenPractice])assert.equal(fn(old,'not-valid'),old)
let all={}
for(const item of PRACTICES)all=completePractice(all,item.id,'','2026-09-25')
assert.equal(completedPractices(all).length,12)
assert.equal(nextPractice(all),null)
assert.equal(nextPractice(reopenPractice(all,'curious')).id,'curious')
const backup={format:'intimate-backup',version:2,self:completed,people:[{communication:{relationshipStage:6},friendScore:70}]}
assert.deepEqual(JSON.parse(JSON.stringify(backup)),backup)
console.log('PASS: 12 complete exercises, selection, clear/retry/pause, notes preserved, no duplicate clears, all-complete state, legacy fields and backup')
