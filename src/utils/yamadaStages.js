export function getStage(person){
  const raw=person?.communication?.relationshipStage
  if(typeof raw!=='number'&&typeof raw!=='string')return null
  const n=Number(raw)
  return Number.isInteger(n)&&n>=1&&n<=10?n:null
}
export function normalizeGender(value){
  if(['男','男性','male'].includes(value))return 'male'
  if(['女','女性','female'].includes(value))return 'female'
  return null
}
export function resolveMode(person,self){
  const a=normalizeGender(self?.gender),b=normalizeGender(person?.gender)
  if(a&&b)return {id:a===b?'friends':'someone',automatic:true}
  const chosen=person?.yamada?.mode
  return {id:['friends','someone'].includes(chosen)?chosen:null,automatic:false}
}
export function guidesFor(mode){return mode==='someone'?SOMEONE_GUIDES:FRIEND_GUIDES}
export function setStage(person,stage){
  if(stage!==null&&(!Number.isInteger(stage)||stage<1||stage>10))return person
  return {...person,communication:{...person.communication,relationshipStage:stage}}
}
